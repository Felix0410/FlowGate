-- 在专用数据库中执行；只创建缺失对象，不删除或覆盖已有业务数据。
CREATE TABLE IF NOT EXISTS fg_service (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, code VARCHAR(200) NOT NULL UNIQUE,
 name VARCHAR(200) NOT NULL, upstream_uri VARCHAR(300) NOT NULL, enabled BOOLEAN NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS fg_api (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, service_id BIGINT NOT NULL, method VARCHAR(10) NOT NULL,
 public_path VARCHAR(300) NOT NULL, upstream_path VARCHAR(300) NOT NULL,
 is_public BOOLEAN NOT NULL, required_scope VARCHAR(100) NOT NULL DEFAULT '', enabled BOOLEAN NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (service_id) REFERENCES fg_service(id)
);
CREATE TABLE IF NOT EXISTS fg_route (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, api_id BIGINT NOT NULL UNIQUE,
 route_id VARCHAR(200) NOT NULL UNIQUE, priority INT NOT NULL, enabled BOOLEAN NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (api_id) REFERENCES fg_api(id)
);
CREATE TABLE IF NOT EXISTS fg_policy (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, code VARCHAR(200) NOT NULL UNIQUE,
 type VARCHAR(30) NOT NULL, scope VARCHAR(30) NOT NULL, parameters_json JSON NOT NULL, enabled BOOLEAN NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS fg_policy_binding (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, policy_id BIGINT NOT NULL, target_type VARCHAR(30) NOT NULL,
 target_id BIGINT NOT NULL, UNIQUE(policy_id,target_type,target_id),
 FOREIGN KEY (policy_id) REFERENCES fg_policy(id)
);
CREATE TABLE IF NOT EXISTS fg_principal (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, principal_type VARCHAR(20) NOT NULL,
 username VARCHAR(200) NOT NULL UNIQUE, password_hash VARCHAR(100), role VARCHAR(20) NOT NULL,
 scopes_json JSON NOT NULL, enabled BOOLEAN NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS fg_config_state (
 id BIGINT PRIMARY KEY, current_version BIGINT NOT NULL, optimistic_version BIGINT NOT NULL
);
INSERT IGNORE INTO fg_config_state(id,current_version,optimistic_version) VALUES(1,0,0);
CREATE TABLE IF NOT EXISTS fg_config_release (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, version BIGINT NOT NULL UNIQUE,
 snapshot_json JSON NOT NULL, sha256 CHAR(64) NOT NULL, actor_id BIGINT NOT NULL,
 rollback_from BIGINT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS fg_audit_log (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor_id BIGINT NOT NULL, action VARCHAR(50) NOT NULL,
 target_type VARCHAR(50) NOT NULL, target_id VARCHAR(200) NOT NULL,
 release_version BIGINT, summary VARCHAR(300) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_id(id)
);
CREATE TABLE IF NOT EXISTS fg_release_node (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, node_id VARCHAR(200) NOT NULL UNIQUE,
 applied_version BIGINT NOT NULL, checksum CHAR(64) NOT NULL, last_seen_at TIMESTAMP NOT NULL
);
